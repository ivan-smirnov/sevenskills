const lessonFactory = (
  skillId: SkillId,
  level: number,
  title: string,
  summary: string,
  concept: string,
  example: string,
  prompt: string,
  choices: Lesson["exercise"]["choices"],
  reflectionPrompt: string,
  actionPrompt: string,
): Lesson => ({
  id: `${skillId}-${level}`,
  skillId,
  level,
  title,
  duration: level === 1 ? "3 мин" : level === 2 ? "5 мин" : "7 мин",
  summary,
  concept,
  example,
  exercise: { prompt, choices },
  reflectionPrompt,
  actionPrompt,
});

